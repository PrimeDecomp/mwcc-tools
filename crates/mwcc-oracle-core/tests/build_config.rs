use mwcc_oracle_core::build_config::{self, Platform, Request};
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::{fs, path::PathBuf};
fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures/build-config")
}
fn normalize(text: &str) -> String {
    let mut lines = vec![];
    for line in text.lines() {
        if ["# Generated by ", "python = ", "tools = ", "tools_dep = "]
            .iter()
            .any(|p| line.starts_with(p))
        {
            continue;
        }
        // Frozen C graphs predate explicit producer selection in regeneration.
        lines.push(
            line.replace("build/tools/objdiff-cli.exe", "build/tools/objdiff-cli")
                .replace(" --oracle --producer c", " --oracle"),
        );
    }
    lines.join("\n") + "\n"
}
fn project() -> tempfile::TempDir {
    let metadata: Value =
        serde_json::from_slice(&fs::read(fixtures().join("project.json")).unwrap()).unwrap();
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path();
    fs::create_dir_all(root.join("config")).unwrap();
    fs::write(
        root.join("config/sources.json"),
        serde_json::to_vec(&metadata["sources"]).unwrap(),
    )
    .unwrap();
    for (version, config) in metadata["configs"].as_object().unwrap() {
        let path = root.join("config").join(version);
        fs::create_dir_all(&path).unwrap();
        fs::write(
            path.join("config.json"),
            serde_json::to_vec(config).unwrap(),
        )
        .unwrap();
        if let Some(splits) = metadata["splits"][version].as_str() {
            fs::write(path.join("splits.txt"), splits).unwrap();
        }
    }
    directory
}
#[test]
fn native_configuration_preserves_all_reference_graphs() {
    let root = project();
    let cases: Vec<Value> =
        serde_json::from_slice(&fs::read(fixtures().join("cases.json")).unwrap()).unwrap();
    for (i, case) in cases.iter().enumerate() {
        let request = Request {
            version: case["version"].as_str().unwrap().into(),
            mode: case["mode"].as_str().map(str::to_owned),
            split_only: case["split_only"].as_bool().unwrap(),
            oracle: case["oracle"].as_bool().unwrap(),
            rust_hooks: false,
            tools: "/opt/mwcc tools/mwcc-tools".into(),
            platform: serde_json::from_value(case["platform"].clone()).unwrap(),
        };
        let generated = build_config::generate(root.path(), &request).unwrap();
        // The native API makes --oracle imply linking. The old Python API
        // silently ignored it in GC 1.3's default compare mode. Compare those
        // two requests with the frozen explicit-link oracle graph instead.
        let expected = if request.oracle && case["mode"].is_null() {
            cases
                .iter()
                .find(|other| {
                    other["version"] == case["version"]
                        && other["platform"] == case["platform"]
                        && other["split_only"] == case["split_only"]
                        && other["oracle"] == true
                        && other["mode"] == "link"
                })
                .unwrap()
        } else {
            case
        };
        if request.platform.windows() {
            assert!(
                generated
                    .ninja
                    .contains("build build/tools/objdiff-cli.exe: download")
            );
        } else {
            assert!(
                generated
                    .ninja
                    .contains("build build/tools/objdiff-cli: download")
            );
        }
        assert_eq!(
            normalize(&generated.ninja),
            expected["ninja"].as_str().unwrap(),
            "case {i}: {} {}",
            case["version"],
            case["platform"]
        );
        assert_eq!(
            serde_json::to_value(generated.objdiff).unwrap(),
            expected["objdiff"],
            "case {i}"
        );
    }
}
#[test]
fn compiler_argument_quoting_matches_python_on_both_platforms() {
    let root = fixtures();
    let manifest: Value =
        serde_json::from_slice(&fs::read(root.join("manifest.json")).unwrap()).unwrap();
    assert_eq!(
        manifest["reference_commit"],
        "b75c4e5e0b4bc97ae06c26ea9d6aad8379ac1722"
    );
    for (name, hash) in manifest["files"].as_object().unwrap() {
        assert_eq!(
            format!("{:x}", Sha256::digest(fs::read(root.join(name)).unwrap())),
            hash.as_str().unwrap(),
            "{name}"
        );
    }
    let cases: Vec<Value> =
        serde_json::from_slice(&fs::read(fixtures().join("quotes.json")).unwrap()).unwrap();
    for case in cases {
        for (name, platform) in [("Windows", Platform::Windows), ("Posix", Platform::Posix)] {
            assert_eq!(
                build_config::quote(case["argument"].as_str().unwrap(), platform),
                case[name].as_str().unwrap()
            );
        }
    }
    let args: Vec<_> = ["-c", "-DNAME=x", "source.c", "-o", "out.obj"]
        .into_iter()
        .map(str::to_owned)
        .collect();
    assert_eq!(
        build_config::pro4_arguments(&args).unwrap(),
        ["/c", "/DNAME=x", "source.c", "/Foout.obj"]
    );
}
#[test]
fn depfile_conversion_matches_native_reference_and_preserves_failed_inputs() {
    let name = if cfg!(windows) {
        "depfiles-Windows.json"
    } else {
        "depfiles-Posix.json"
    };
    let reference: Value =
        serde_json::from_slice(&fs::read(fixtures().join(name)).unwrap()).unwrap();
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path();
    fs::create_dir(root.join("out")).unwrap();
    for case in reference["cases"].as_array().unwrap() {
        let text = case["input"]
            .as_str()
            .unwrap()
            .replace("{ROOT}", &root.to_string_lossy().replace('\\', "/"))
            .replace("{BACKROOT}", &root.to_string_lossy().replace('/', "\\"));
        let data: Vec<u8> = text.chars().map(|c| c as u8).collect();
        fs::write(root.join("input.dep"), data).unwrap();
        let output = case["output"].as_str().unwrap();
        build_config::depfile::run(root, std::path::Path::new("input.dep"), output).unwrap();
        let expected = case["text"].as_str().unwrap();
        let expected = if cfg!(windows) {
            expected.replace('\n', "\r\n")
        } else {
            expected.to_owned()
        }
        .into_bytes();
        assert_eq!(
            fs::read(root.join(format!("{output}.d"))).unwrap(),
            expected,
            "{case}"
        );
        assert!(!root.join("input.dep").exists());
    }
    fs::write(root.join("input.dep"), b"target.obj: file.h\n").unwrap();
    assert!(
        build_config::depfile::run(root, std::path::Path::new("input.dep"), "absent/obj").is_err()
    );
    assert!(root.join("input.dep").is_file());
}

#[test]
fn rust_hook_builds_are_regenerable_and_require_the_migrated_abi() {
    let root = project();
    let mut request = Request {
        version: "GC_1_3".into(),
        mode: Some("link".into()),
        split_only: false,
        oracle: false,
        rust_hooks: true,
        tools: "mwcc-tools".into(),
        platform: Platform::current(),
    };
    assert!(
        build_config::generate(root.path(), &request)
            .unwrap_err()
            .to_string()
            .contains("requires --oracle")
    );
    request.oracle = true;
    request.mode = Some("compare".into());
    assert!(
        build_config::generate(root.path(), &request)
            .unwrap_err()
            .to_string()
            .contains("requires --mode link")
    );
    request.mode = Some("link".into());
    assert!(build_config::generate(root.path(), &request).is_err());
    let path = root.path().join("config/GC_1_3/config.json");
    let mut config: Value = serde_json::from_slice(&fs::read(&path).unwrap()).unwrap();
    config["oracle"]["hooks"] = serde_json::json!(
        mwcc_oracle_core::producer::HOOKS
            .into_iter()
            .chain(mwcc_oracle_core::producer::frontend_hooks("GC_1_3").unwrap())
            .collect::<Vec<_>>()
    );
    fs::write(path, serde_json::to_vec(&config).unwrap()).unwrap();
    let ninja = build_config::generate(root.path(), &request).unwrap().ninja;
    assert!(ninja.contains("--oracle --producer rust"));
    assert!(ninja.contains("command = $tools build-hooks $out"));
    assert!(ninja.contains("--frontend-version GC_1_3"));
    assert!(ninja.contains("build/GC_1_3/oracle/compiled/rust/frontend.obj"));
    assert!(!ninja.contains("compiled/src/oracle/Hooks.c.obj"));
    assert!(ninja.contains("build/GC_1_3/oracle/compiled/rust/hooks.obj"));
    assert!(ninja.contains("command = $tools build-hooks $out --trace-shim"));
    assert!(ninja.contains("build build/GC_1_3/oracle/OracleTrace.obj: rust_trace"));
    assert!(!ninja.contains("build build/GC_1_3/oracle/OracleTrace.obj: mwcc"));
    for file in mwcc_oracle_core::producer::TRACE_SOURCES {
        assert!(ninja.contains(&format!("crates/mwcc-oracle-hooks/src/{file}")));
    }
    for file in mwcc_oracle_core::producer::SOURCES {
        assert!(ninja.contains(&format!("crates/mwcc-oracle-hooks/src/{file}")));
    }
}
