"""Freeze compiler quoting, Ninja graphs and objdiff configuration on synthetic projects."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import os
import re
import shlex
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT / "tests/fixtures/build-config"
VERSIONS=["GC_1_0","GC_1_1","GC_1_1p1","GC_1_2_5","GC_1_2_5n","GC_1_3","GC_1_3_2","GC_2_7"]


def normalize_ninja(text):
    lines=[]
    for line in text.splitlines():
        if line.startswith(("# Generated by ","python = ","tools = ","tools_dep = ")):
            continue
        for old,new in (("$python tools/download_tool.py","$tools download"),("$python tools/transform_dep.py","$tools transform-dep"),
                        ("$python configure.py","$tools configure"),("$python tools/link.py","$tools link"),
                        ("$python tools/split.py","$tools split"),("$python tools/implib.py","$tools implib"),
                        ("$python tools/compare.py","$tools compare"),("tools/split.py tools/pe.py","$tools_dep"),
                        ("tools/compare.py tools/pe.py","$tools_dep"),("tools/link.py","$tools_dep"),
                        ("tools/implib.py","$tools_dep"),("configure | configure.py ","configure | $tools_dep ")):
            line=line.replace(old,new)
        line=re.sub(r"config\\(GC_[^\\ ]+)\\splits\.txt",r"config/\1/splits.txt",line)
        lines.append(line)
    return "\n".join(lines)+"\n"


def project():
    sources={"src/a.c":dict(compiler="pro53",flags=["-O4,p","-inline","auto,deferred","-sym","off","-DMSG=one two"],include_dirs=["include extra"],system_include_dirs=["sdk"]),
             "src/runtime/main.c":dict(compiler="pro4",flags=["-O4","-sym","on"]),
             "src/driver/CLWriteObjectFile.c":dict(compiler="pro5",flags=["-O4"]),
             "src/local.cpp":dict(compiler="pro53",flags=["-O4"],status="NonMatching")}
    splits="Sections:\n\t.text type:code align:16\n\t.data type:data align:8\n\t.bss type:bss align:8\n"
    for i,unit in enumerate([*sources,"cexc.obj","ccinit.obj","generated"]):
        splits+=f"{unit}:\n\t.text start:0x{0x401000+16*i:08x} end:0x{0x401010+16*i:08x}\n"
    splits+="common:\n\t.bss start:0x00403000 end:0x00403008\n"
    configs={}
    for version in VERSIONS:
        config=dict(original=f"build/compilers/GC/{version[3:].replace('_','.')}/mwcceppc.exe")
        if version=="GC_1_3":
            config.update(mode="compare",compilers={"pro5":"pro53","pro53":"pro6"},compiler_overrides={"src/a.c":"pro5"},
                          flags={"-O4":"-O3"},sym_on=["src/a.c"],sym_off=["src/runtime/main.c"])
        if version in ("GC_1_3_2","GC_2_7"):
            config.update(matching=[],imports=["config/kernel.def","config/version.def"])
        if version=="GC_1_2_5n":
            config["matching"]=["src/local.cpp"]
        if version in ("GC_1_3","GC_1_3_2","GC_2_7"):
            config["oracle"]=dict(template="src/a.c",units=["src/a.c"] if version=="GC_1_3" else [],extra=["src/oracle/Hooks.c"],hooks=["_entry"])
        configs[version]=config
    return dict(sources=sources,configs=configs,splits={v:splits.replace("src/a.c:","\t.rsrc type:data align:4\nsrc/a.c:") if v in ("GC_1_3_2","GC_2_7") else splits for v in VERSIONS if v!="GC_1_0"})


def stage(directory,metadata):
    (directory / "config").mkdir(parents=True)
    (directory / "config/sources.json").write_text(json.dumps(metadata["sources"]))
    for version,config in metadata["configs"].items():
        destination=directory / "config" / version
        destination.mkdir()
        (destination / "config.json").write_text(json.dumps(config))
        if version in metadata["splits"]:
            (destination / "splits.txt").write_text(metadata["splits"][version])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oracle-root",type=Path,required=True)
    args=parser.parse_args()
    sys.path.insert(0,str(args.oracle_root / "tools"))
    spec=importlib.util.spec_from_file_location("reference_configure",args.oracle_root / "configure.py")
    configure=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(configure)
    OUT.mkdir(parents=True,exist_ok=True)
    metadata=project()
    (OUT / "project.json").write_text(json.dumps(metadata,indent=2)+"\n")
    quotes=[]
    for text in ("","plain","one two","a\tb",'a"b',"a\\","two words\\",'path\\"name',"héllo","$HOME","a'b","C:\\SDK\\some path\\",r"back\\slash"):
        quotes.append(dict(argument=text,Windows=subprocess.list2cmdline([text]),Posix=shlex.quote(text)))
    (OUT / "quotes.json").write_text(json.dumps(quotes,indent=2)+"\n")
    cases=[]
    requests=[]
    for version in VERSIONS:
        requests.extend([dict(version=version,mode=None,split_only=False,oracle=False),dict(version=version,mode="compare",split_only=False,oracle=False)])
        if version!="GC_1_0":
            requests.append(dict(version=version,mode="link",split_only=True,oracle=False))
        if version in ("GC_1_3","GC_1_3_2","GC_2_7"):
            requests.append(dict(version=version,mode="link",split_only=False,oracle=True))
    requests.append(dict(version="GC_1_3",mode=None,split_only=False,oracle=True))
    with tempfile.TemporaryDirectory() as temporary:
        directory=Path(temporary)
        stage(directory,metadata)
        previous=Path.cwd()
        try:
            os.chdir(directory)
            for platform in ("Windows","Posix"):
                configure.WINDOWS=platform=="Windows"
                configure.TOOL_DEP="" if configure.WINDOWS else "$wibo "
                configure.ENVIRONMENT="cmd /c set MWCIncludes=include/libc&& " if configure.WINDOWS else "MWCIncludes=include/libc "
                configure.STUB=" build/compilers/{}/lmgr326b.dll" if configure.WINDOWS else ""
                configure.STUB_INPUT=" | tools/lmgr_stub/lmgr326b.dll" if configure.WINDOWS else ""
                for request in requests:
                    if Path("objdiff.json").exists():
                        Path("objdiff.json").unlink()
                    sys.argv=["configure.py","--version",request["version"]]
                    if request["mode"]:
                        sys.argv += ["--mode",request["mode"]]
                    if request["split_only"]:
                        sys.argv.append("--split-only")
                    if request["oracle"]:
                        sys.argv.append("--oracle")
                    configure.main()
                    cases.append(dict(**request,platform=platform,ninja=normalize_ninja(Path("build.ninja").read_text()),
                                      objdiff=json.loads(Path("objdiff.json").read_text()) if Path("objdiff.json").exists() else None))
        finally:
            os.chdir(previous)
    (OUT / "cases.json").write_text(json.dumps(cases,indent=2)+"\n")
    manifest=dict(reference_commit=subprocess.check_output(["git","-C",str(args.oracle_root),"rev-parse","HEAD"],text=True).strip(),
                  reference_sha256=hashlib.sha256((args.oracle_root / "configure.py").read_bytes()).hexdigest(),
                  files={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in OUT.iterdir() if p.is_file() and p.name!="manifest.json"})
    (OUT / "manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print(f"Captured {len(cases)} cross-platform configuration cases")


if __name__=="__main__":
    main()
