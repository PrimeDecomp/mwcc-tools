"""Compare native import/resource conversion with the pinned Python build tools."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oracle-root", type=Path, required=True)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--keep", type=Path)
    args = parser.parse_args()
    results = []
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        commands = [("implib", args.oracle_root / "config/lmgr326b.def")]
        commands += [("rsrc2res", args.oracle_root / "build/compilers/GC" / version / "mwcceppc.exe")
                     for version in ("1.0", "1.1", "1.1p1", "1.2.5", "1.2.5n", "1.3", "1.3.2", "2.7")]
        for index, (command, source) in enumerate(commands):
            python_output, rust_output = root / f"{index}.python", root / f"{index}.rust"
            python = subprocess.run([sys.executable, str(args.oracle_root / "tools" / f"{command}.py"), str(source), str(python_output)], capture_output=True, text=True)
            rust = subprocess.run([str(args.binary.resolve()), command, str(source), str(rust_output)], capture_output=True, text=True)
            if command == "rsrc2res" and python.returncode and rust.returncode and "StopIteration" in python.stderr and "PE image has no .rsrc section" in rust.stderr:
                results.append({"command": command, "input": str(source), "resources_present": False, "both_rejected_missing_section": True})
                continue
            if python.returncode or rust.returncode:
                raise RuntimeError(f"{source}: Python {python.stderr}; Rust {rust.stderr}")
            expected, actual = python_output.read_bytes(), rust_output.read_bytes()
            if actual != expected:
                raise RuntimeError(f"{source}: generated bytes differ")
            results.append({"command": command, "input": str(source), "bytes": len(actual), "sha256": hashlib.sha256(actual).hexdigest(), "identical": True})
    if args.keep:
        args.keep.parent.mkdir(parents=True, exist_ok=True)
        args.keep.write_text(json.dumps(results, indent=2)+"\n")
    converted = sum(r.get("identical", False) for r in results)
    print(f"{converted} import/resource conversions are byte-identical; {len(results)-converted} absent resource sections rejected by both")


if __name__ == "__main__":
    main()
